"""
보상 함수 모듈 (v1)

[보상을 고른 이유]
1. 설계 카드 4절의 성공 척도인 '28일간 누적 순이익(매출 - 원가)'을 가장 단순하게 하루치(당일 순이익)로 옮겼습니다.
2. 불필요한 인위적 가공이나 복잡한 벌점 없이, 매장이 실제로 번 돈을 그대로 에이전트의 목표로 삼기 위함입니다.
3. 원화 금액(수십만 원 단위)이 너무 커서 신경망 학습이 흔들리지 않도록 10만 원 단위(1.0)로 나누어 안정화했습니다.
"""

# ==============================================================================
# [가정값 묶음] (규칙 6)
# ==============================================================================
# 보상 크기 안정화를 위한 스케일링 나눗수 (10만 원 = 1.0)
REWARD_SCALE = 100_000.0  # 가정: 하루 순이익 수십만 원을 -5.0 ~ +5.0 범위로 맞추기 위함


def compute_reward_v1(daily_profit: float, info: dict = None) -> float:
    """
    v1 보상 계산 함수:
    당일 순이익(매출 - 당일 구운 빵 전체 원가)을 REWARD_SCALE(10만 원)로 나눈 값을 돌려줍니다.
    
    Args:
        daily_profit: 당일 순이익 (원화)
        info: 추가 정보 딕셔너리 (v2 이후 확장용)
        
    Returns:
        scaled_reward: 정규화된 실수 보상값
    """
    scaled_reward = float(daily_profit) / REWARD_SCALE
    return scaled_reward
